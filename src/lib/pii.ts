// Скрытие персональных данных клиента банка перед отправкой текста ИИ и сохранением в историю:
// ФИО, телефоны, даты рождения, паспорт / ID-карта, ПИНФЛ, номера карт и счетов, e-mail.
// Данные заменяются метками вида [ТЕЛЕФОН] — ИИ их не видит и не может «прочитать».
// Правила консервативные: лучше скрыть лишнее (например, суммы похожие на номер), чем пропустить личные данные.

export type PiiKind = "ФИО" | "ИМЯ" | "ТЕЛЕФОН" | "ДАТА РОЖДЕНИЯ" | "ПАСПОРТ" | "ПИНФЛ" | "КАРТА" | "СЧЁТ" | "EMAIL";

const U = "А-ЯЁA-ZЎҚҒҲ"; // заглавные буквы (русские, латиница, узбекская кириллица)
const L = "а-яёa-zўқғҳ'ʻʼ‘’-"; // строчные и апострофы в узбекских именах (Oʻ, gʻ)
const WORD = `[${U}][${L}]+`;

const PATRONYMIC = `[${U}][${L}]*(?:ович|евич|ьич|овна|евна|ична|инична)`;
const UZ_PATRONYMIC = `(?:[Oo]['ʻ‘’]?g['ʻ‘’]?li|[Uu]g['ʻ‘’]?li|[Qq]izi|[Ўў]ғли|[Уу]гли|[Ққ]изи|[Кк]изи)`;
const SURNAME = `[${U}][${L}]*(?:ов|ев|ёв|ин|ын|ова|ева|ёва|ина|ына|ский|цкий|ская|цкая|ov|ev|ova|eva|yev|yeva|in|ina)`;

type Rule = { kind: PiiKind; re: RegExp; keep?: number };

// Год, раньше которого дата считается датой рождения (клиенту не меньше 14 лет).
const adultYear = () => new Date().getFullYear() - 14;

const RULES: Rule[] = [
  { kind: "EMAIL", re: /[\w.+-]+@[\w-]+\.[\w.-]+/g },
  // Номер счёта — 20 цифр; ПИНФЛ — 14 цифр (проверяем раньше карт и телефонов).
  { kind: "СЧЁТ", re: /(?<!\d)\d{20}(?!\d)/g },
  { kind: "ПИНФЛ", re: /(?<!\d)\d{14}(?!\d)/g },
  // Карта: 16 цифр с пробелами/дефисами или с замаскированной серединой (8600 **** **** 1234).
  { kind: "КАРТА", re: /(?<!\d)\d{4}[ -]?(?:\d{4}|\*{4}|x{4}|X{4})[ -]?(?:\d{4}|\*{4}|x{4}|X{4})[ -]?\d{4}(?!\d)/g },
  // Паспорт / ID-карта: 2 буквы + 7 цифр (AA1234567, AD 1234567); с подписью — любые серия и номер.
  { kind: "ПАСПОРТ", re: /(?<![\p{L}\d])[A-ZА-Я]{2}\s?\d{7}(?!\d)/gu },
  { kind: "ПАСПОРТ", re: /((?:паспорт\p{L}*|id[- ]?карт\p{L}*|pasport\p{L}*|passport)[:\s№#]*)([A-ZА-Яa-zа-я]{0,2}\s?\d[\d\s]{5,10}\d)/giu, keep: 1 },
  // Телефон: +998 XX XXX XX XX в разных записях, а также 9 цифр подряд с кодом оператора.
  { kind: "ТЕЛЕФОН", re: /(?<!\d)(?:\+?\s?998[\s\-()]*)?\(?[2-9]\d\)?[\s-]?\d{3}[\s-]?\d{2}[\s-]?\d{2}(?!\d)/g },
  // Дата рождения: по подписи — любая дата; без подписи — дата с годом, когда клиенту было бы 14+ лет.
  { kind: "ДАТА РОЖДЕНИЯ", re: /((?:дат\p{L}*\s+рожд\p{L}*|д\.?\s?р\.?|рожд\p{L}*|tug['ʻ‘’]?il\p{L}*(?:\s+sana\p{L}*)?)[:\s]*)(\d{1,2}[./-]\d{1,2}[./-]\d{2,4}|\d{4}-\d{2}-\d{2})/giu, keep: 1 },
  { kind: "ДАТА РОЖДЕНИЯ", re: /(?<!\d)(\d{1,2})[./](\d{1,2})[./](19\d{2}|20\d{2})(?!\d)/g },
  // ФИО: с отчеством (русским или узбекским «o‘g‘li / qizi»), «Фамилия Имя», по подписи «ФИО:», «меня зовут».
  { kind: "ФИО", re: new RegExp(`(?:${WORD}\\s+){1,2}${PATRONYMIC}`, "gu") },
  { kind: "ФИО", re: new RegExp(`(?:${WORD}\\s+){1,3}${UZ_PATRONYMIC}`, "gu") },
  { kind: "ФИО", re: new RegExp(`${SURNAME}\\s+${WORD}(?:\\s+${WORD})?`, "gu") },
  { kind: "ФИО", re: new RegExp(`((?:ФИО|Ф\\.И\\.О\\.|F\\.I\\.Sh\\.|FISh|[Мм]еня зовут|[Мм]о[её] имя|[Ii]smim|[Mm]ening ismim)[:\\s—-]*)(${WORD}(?:\\s+${WORD}){0,2})`, "gu"), keep: 1 },
  { kind: "ФИО", re: new RegExp(`((?:[Кк]лиент\\p{L}*|[Mm]ijoz\\p{L}*)\\s+)(${SURNAME}(?:\\s+${WORD}){0,2})`, "gu"), keep: 1 },
  // Имя в обращении: «Здравствуйте, Анна!», «Hurmatli Anvar aka».
  { kind: "ИМЯ", re: new RegExp(`((?:[Зз]дравствуйте|[Дд]обрый день|[Дд]обрый вечер|[Дд]оброе утро|[Пп]ривет|[Уу]важаем\\p{L}*|[Hh]urmatli|[Aa]ssalomu alaykum|[Ss]alom)\\s*,?\\s+)(${WORD}(?:\\s+${WORD})?)(?=\\s*[!,.?]|\\s+(?:aka|opa|xonim|janob)(?![\\p{L}]))`, "gu"), keep: 1 },
];

export type MaskResult = { text: string; found: Partial<Record<PiiKind, number>> };

export function maskPII(input: string): MaskResult {
  let text = input;
  const found: Partial<Record<PiiKind, number>> = {};
  for (const { kind, re, keep } of RULES) {
    text = text.replace(re, (...m: string[]) => {
      if (kind === "ДАТА РОЖДЕНИЯ" && !keep) {
        const year = Number(m[3]);
        if (year > adultYear()) return m[0]; // свежая дата — это не дата рождения (платёж, заявка)
      }
      found[kind] = (found[kind] ?? 0) + 1;
      return keep ? `${m[1]}[${kind}]` : `[${kind}]`;
    });
  }
  return { text, found };
}

// Для подсказки сотруднику: «Скрыто: телефон ×1, ФИО ×1».
export const describeMasked = (found: MaskResult["found"]) =>
  Object.entries(found)
    .map(([k, n]) => `${k.toLowerCase()}${n! > 1 ? ` ×${n}` : ""}`)
    .join(", ");
