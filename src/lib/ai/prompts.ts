// Модели иногда оборачивают JSON в ```json или добавляют текст вокруг.
export function parseJson<T>(raw: string): T {
  const cleaned = raw.replace(/```json|```/g, "").trim();
  try {
    return JSON.parse(cleaned);
  } catch {}
  const start = cleaned.search(/[[{]/);
  const end = Math.max(cleaned.lastIndexOf("]"), cleaned.lastIndexOf("}"));
  if (start >= 0 && end > start) {
    try {
      return JSON.parse(cleaned.slice(start, end + 1));
    } catch {}
  }
  // Ответ обрезан на середине (кончился лимит вывода) — забираем все элементы
  // массива, которые успели прийти целиком.
  const salvaged = salvageArray(cleaned.slice(Math.max(start, 0)));
  if (salvaged) return salvaged as T;
  throw new Error("ИИ вернул неполный ответ — попробуйте ещё раз");
}

// Из начала JSON-массива "[{...},{...},{..." оставляет только законченные объекты верхнего уровня.
function salvageArray(text: string): unknown[] | null {
  if (!text.startsWith("[")) return null;
  let depth = 0;
  let inString = false;
  let escaped = false;
  let lastComplete = -1;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inString) {
      if (escaped) escaped = false;
      else if (c === "\\") escaped = true;
      else if (c === '"') inString = false;
      continue;
    }
    if (c === '"') inString = true;
    else if (c === "{" || c === "[") depth++;
    else if (c === "}" || c === "]") {
      depth--;
      if (depth === 1 && c === "}") lastComplete = i;
    }
  }
  if (lastComplete < 0) return null;
  try {
    const list = JSON.parse(text.slice(0, lastComplete + 1) + "]");
    return Array.isArray(list) && list.length ? list : null;
  } catch {
    return null;
  }
}

const isChoice = (q: GeneratedQuestion) => q.type === "MULTIPLE_CHOICE" || q.type === "BEST_RESPONSE";

// Отбрасываем некорректные задания и типы, недопустимые на уровне; при заданном mix — не больше, чем просили, каждого вида.
function normalizeQuestions(list: GeneratedQuestion[], level: Level, mix?: QuestionMix): GeneratedQuestion[] {
  const valid = (Array.isArray(list) ? list : []).filter((q) => {
    if (!q?.text || !q.type) return false;
    if (isChoice(q)) return Array.isArray(q.options) && q.options.length >= 2 && typeof q.correctIndex === "number";
    return OPEN_TYPES[level].includes(q.type);
  });
  if (!mix) return valid;
  return [...valid.filter(isChoice).slice(0, mix.choice), ...valid.filter((q) => !isChoice(q)).slice(0, mix.open)];
}

